-- ----------------------------------------------------------------------------
-- mod-procedural-dungeon: Round E retunes the finale cache template loot
--
-- The five FL mats 920100-920104 that mod_pdungeon_chromie.sql puts into
-- gameobject_loot_template 910068 were the C8.1 PLACEHOLDER content: 100 % each,
-- so the finale had something to hand out until the real reward table existed.
--
-- Round E is that table, and it is added at RUNTIME, not here: spec section 3
-- L4 injects the rolled gear plus the T4/T5 currency and the L5 legacy-rare
-- bonus hits into go->loot from PDv2ChestLootScript, on
-- OnGameObjectLootStateChanged(go, GO_ACTIVATED, unit) - the hook the core
-- reaches after Player::SendLoot has already filled the template loot and
-- before the loot packet goes out. So the template rows keep being read; they
-- just stop being the reward and become filler. Five guaranteed mat stacks on
-- top of the real payout would drown it, hence 25 % each: on average a bit
-- over one mat stack per cache instead of five.
--
-- Why an UPDATE and not a DELETE + INSERT: mod_pdungeon_chromie.sql owns those
-- five rows including their Min/MaxCount ladder (3-5 / 2-4 / 1-2 / 1 / 1), and
-- Round E changes exactly one column of them. UpdateFetcher::PathCompare
-- compares filename().string() and '.' (0x2E) sorts before '_' (0x5F), so
-- mod_pdungeon_chromie.sql always applies before mod_pdungeon_chromie_loot_e.sql
-- and the rows exist by the time this runs, on a fresh database as well as on
-- this one. The statement is idempotent - re-applying it writes the same 25.
--
-- Trap for whoever edits mod_pdungeon_chromie.sql next: the updater applies each
-- file once by hash, so a rehash of THAT file re-inserts Chance 100 without
-- re-running this one. Fold the 25 into it, or delete this file at the same time.
--
-- Measured 2026-09-10 against the live world DB: the five rows are present at
-- Chance 100, LootMode 1, GroupId 0, so this UPDATE matches exactly five rows.
-- ----------------------------------------------------------------------------

UPDATE `gameobject_loot_template` SET `Chance` = 25 WHERE `Entry` = 910068 AND `Item` IN (920100, 920101, 920102, 920103, 920104);
